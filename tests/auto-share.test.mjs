import assert from 'node:assert'
import { mkdirSync, rmSync } from 'node:fs'
const DIR='/tmp/dy-as-'+process.pid; process.env.DY_MEMORY_DIR=DIR; rmSync(DIR,{recursive:true,force:true}); mkdirSync(DIR,{recursive:true})
const {openDb}=await import('../lib/store/db.js'); const {insertMemory}=await import('../lib/store/memories.js')
const {classifyShare,shareNewMemory}=await import('../lib/share/auto.js')
const out={ok:true,test:'auto-share'}
const {db}=openDb(DIR)
assert.equal(classifyShare({text:'今天在看海',scopeType:'public'}).share,true)
assert.equal(classifyShare({text:'今天在看海',scopeType:'owner',fromSelf:true}).share,false,'owner 不共享')
assert.equal(classifyShare({text:'主人邮箱 a@b.com',scopeType:'public',fromSelf:true}).reason,'privacy')
assert.equal(classifyShare({text:'今天在看海',scopeType:'contact'}).share,false)
let r=await shareNewMemory(db,{id:1,text:'今天在看海',scopeType:'public',cfg:{autoShare:false},insertMemory})
assert.equal(r.share,false); assert.equal(db.prepare('select count(*) c from memories').get().c,0)
r=await shareNewMemory(db,{id:2,text:'今天在学习看海',scopeType:'public',cfg:{autoShare:true},insertMemory})
assert.equal(r.share,true); const copy=db.prepare('select * from memories where id=?').get(r.id)
assert.ok(copy.text.startsWith('[汐的近况]')); assert.equal(copy.scope_type,'public')
r=await shareNewMemory(db,{id:2,text:'今天在学习看海',scopeType:'public',cfg:{autoShare:true},insertMemory})
assert.equal(r.reason,'duplicate')
r=await shareNewMemory(db,{id:3,text:'今天心情好',scopeType:'owner',fromSelf:true,cfg:{autoShare:true},insertMemory})
assert.equal(r.share,false)
const aud=db.prepare('select * from memory_share').all()
assert.ok(aud.some(a=>a.reason==='owner'&&a.ok===0)); assert.ok(aud.some(a=>a.ok===1))
assert.ok(!aud.some(a=>String(a.reason).includes('心情')),'审计不记原文')
r=await shareNewMemory(db,{id:4,text:'今天在学习',scopeType:'public',cfg:{autoShare:true,autoShareLlm:true},llm:()=>{throw new Error('x')},insertMemory})
assert.equal(r.share,false); assert.ok(db.prepare("select * from memory_share where reason='llm-failed'").get())
console.log(JSON.stringify(out))
