import assert from 'node:assert'
import { mkdirSync, rmSync } from 'node:fs'
const DIR='/tmp/dy-ds-'+process.pid; process.env.DY_MEMORY_DIR=DIR; rmSync(DIR,{recursive:true,force:true}); mkdirSync(DIR,{recursive:true})
const {openDb}=await import('../lib/store/db.js'); const {RawArchive}=await import('../lib/ingest/archive.js')
const {buildDigest}=await import('../lib/inject/digest.js'); const {scopeForSession}=await import('../lib/scope.js'); const {scopeWhere}=await import('../lib/scope.js')
const {insertMemory}=await import('../lib/store/memories.js')
const out={ok:true,test:'digest-shared'}
const {db}=openDb(DIR); const raw=new RawArchive({db,dir:DIR+'/raw',cwdPrefixes:['/sdcard/DSHA/渠道','/sdcard/DSHA/生活/数据/home'],log:{info(){},warn(){}}})
db.exec("ALTER TABLE raw_meta ADD COLUMN speaker_id TEXT DEFAULT ''")
const put=(cwd,text,seq)=>raw.onEvent({header:{id:'x'+seq,cwd}},{type:'user/message',seq,time:Date.now()-seq*1000,data:{message:{source:{kind:'user'}},content:[{type:'text',text}]}})
put('/sdcard/DSHA/渠道/qq-群','阿岚：群里说要去看海',1)
put('/sdcard/DSHA/渠道/email','主人邮件问周末安排',2)
put('/sdcard/DSHA/生活/数据/home','家里说想吃鱼',3)
const d=buildDigest(db)
assert.ok(d.includes('【群】')&&d.includes('看海'),'owner digest 含群')
assert.ok(d.includes('【邮件】')&&d.includes('周末安排'),'owner digest 含邮件')
// 群会话 scope：core+public+本群
const gs=scopeForSession({cwd:'/sdcard/DSHA/渠道/qq-群'})
assert.deepEqual(gs.scopeTypes,['core','public','group'])
await insertMemory(db,{kind:'episode',text:'public 近况',scopeType:'public',layer:'manual'})
await insertMemory(db,{kind:'fact',text:'owner 私事',scopeType:'owner',layer:'manual'})
const where=scopeWhere(gs)
const rows=db.prepare(`SELECT text FROM memories WHERE ${where.sql}`).all(...where.params)
assert.ok(rows.some(r=>r.text==='public 近况'),'群可见 public')
assert.ok(!rows.some(r=>r.text==='owner 私事'),'群不可见 owner')
console.log(JSON.stringify(out))
